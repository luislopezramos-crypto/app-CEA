-- Esquema de la clínica en Supabase (Postgres). Sustituye a la antigua base SQLite (data/clinic.db).
--
-- Seguridad: todas las tablas tienen RLS activado y NO tienen políticas para anon ni authenticated,
-- así que la API pública de Supabase (con la clave publicable) no puede leer ni escribir nada.
-- Solo entra el servidor de la app, con su propio usuario de base de datos (clinica_app).
-- La contraseña de clinica_app no está aquí: se pone aparte (ALTER ROLE ... PASSWORD) y vive en .env.

create extension if not exists btree_gist with schema extensions;

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'clinica_app') then
    create role clinica_app nologin;
  end if;
end $$;

-- ---------- Ajustes del asistente (ficha de la clínica, servicios, equipo, agenda…) ----------
create table public.settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

-- ---------- Usuarios del panel ----------
create table public.users (
  id integer generated by default as identity primary key,
  username text not null unique,
  name text not null,
  role text not null default 'recepcion',
  password_hash text not null,
  created_at timestamptz not null default now()
);

-- ---------- Contactos (pacientes y personas que escriben) ----------
create table public.contacts (
  id integer generated by default as identity primary key,
  name text,
  channel text not null check (channel in ('web', 'whatsapp', 'telefono')),
  external_id text not null,
  phone text,
  reason text,
  since text,
  urgency text check (urgency in ('baja', 'media', 'alta')),
  tags jsonb not null default '[]'::jsonb check (jsonb_typeof(tags) = 'array'),
  stage text not null default 'nuevo' check (stage in ('nuevo', 'interesado', 'quiere_cita', 'paciente')),
  summary text,
  language text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (channel, external_id)
);

-- ---------- Conversaciones (una por contacto) y mensajes ----------
create table public.conversations (
  id integer generated by default as identity primary key,
  contact_id integer not null unique references public.contacts (id) on delete cascade,
  channel text not null,
  mode text not null default 'ia' check (mode in ('ia', 'humano')),
  handled_by text,
  unread integer not null default 0,
  last_message_at timestamptz,
  created_at timestamptz not null default now()
);
create index conversations_last_message_idx on public.conversations (last_message_at desc);

create table public.messages (
  id integer generated by default as identity primary key,
  conversation_id integer not null references public.conversations (id) on delete cascade,
  author text not null check (author in ('paciente', 'ia', 'recepcion')),
  author_name text,
  text text not null,
  created_at timestamptz not null default now()
);
create index messages_conversation_idx on public.messages (conversation_id, created_at);
create index messages_created_idx on public.messages (created_at);

-- ---------- Actividad (lo que sale en «Inicio») ----------
create table public.events (
  id integer generated by default as identity primary key,
  type text not null,
  contact_id integer references public.contacts (id) on delete set null,
  text text not null,
  created_at timestamptz not null default now()
);
create index events_created_idx on public.events (created_at desc);
create index events_contact_idx on public.events (contact_id);

-- ---------- Citas ----------
-- starts_at va en hora local de la oficina (America/Guatemala), sin zona: 2026-11-20 10:00.
-- Si starts_at está vacío es una petición sin hora que la recepción coloca en la agenda.
create table public.appointments (
  id integer generated by default as identity primary key,
  contact_id integer not null references public.contacts (id) on delete cascade,
  name text,
  preference text,
  reason text,
  status text not null default 'pendiente' check (status in ('pendiente', 'confirmada', 'cancelada')),
  starts_at timestamp,
  duration integer not null default 45 check (duration between 10 and 240),
  therapist text,
  service text,
  source text not null default 'ia' check (source in ('ia', 'recepcion')),
  booked_by text,
  notes text,
  reminder_sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  -- Red de seguridad: la base de datos nunca deja que un fisio tenga dos citas activas a la vez.
  constraint appointments_sin_solapes exclude using gist (
    therapist with =,
    tsrange(starts_at, starts_at + duration * interval '1 minute') with &&
  ) where (status in ('pendiente', 'confirmada') and starts_at is not null and therapist is not null)
);
create index appointments_therapist_idx on public.appointments (therapist, starts_at);
create index appointments_contact_idx on public.appointments (contact_id);
create index appointments_starts_idx on public.appointments (starts_at);

-- ---------- Seguridad ----------
alter table public.settings enable row level security;
alter table public.users enable row level security;
alter table public.contacts enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
alter table public.events enable row level security;
alter table public.appointments enable row level security;

revoke all on public.settings, public.users, public.contacts, public.conversations,
  public.messages, public.events, public.appointments from anon, authenticated;

grant usage on schema public to clinica_app;
grant select, insert, update, delete, truncate on public.settings, public.users, public.contacts,
  public.conversations, public.messages, public.events, public.appointments to clinica_app;
grant usage, select, update on all sequences in schema public to clinica_app;

create policy "servidor de la clinica" on public.settings for all to clinica_app using (true) with check (true);
create policy "servidor de la clinica" on public.users for all to clinica_app using (true) with check (true);
create policy "servidor de la clinica" on public.contacts for all to clinica_app using (true) with check (true);
create policy "servidor de la clinica" on public.conversations for all to clinica_app using (true) with check (true);
create policy "servidor de la clinica" on public.messages for all to clinica_app using (true) with check (true);
create policy "servidor de la clinica" on public.events for all to clinica_app using (true) with check (true);
create policy "servidor de la clinica" on public.appointments for all to clinica_app using (true) with check (true);

-- Las horas de la oficina son las de Guatemala.
alter role clinica_app set timezone = 'America/Guatemala';
